ALL_LEVELS = {1: LEVEL1, 2: LEVEL2, 3: LEVEL3, 4: LEVEL4}


def main():
    for level, rows in ALL_LEVELS.items():
        assert len(rows) == 60, f"Level {level} has {len(rows)} rows, expected 60"
        questions_seen = set()
        for row in rows:
            assert len(row) == 6, f"Level {level} row malformed: {row}"
            que, o1, o2, o3, o4, ans = row
            opts = [o1, o2, o3, o4]
            assert ans in opts, f"Level {level}: answer not among options: {row}"
            assert len(set(opts)) == 4, f"Level {level}: duplicate options in row: {row}"
            assert que not in questions_seen, f"Level {level}: duplicate question: {que}"
            questions_seen.add(que)

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "questions"
    ws.append(["que", "option1", "option2", "option3", "option4", "answer", "level"])
    total = 0
    for level in (1, 2, 3, 4):
        for que, o1, o2, o3, o4, ans in ALL_LEVELS[level]:
            ws.append([que, o1, o2, o3, o4, ans, level])
            total += 1

    out_path = "D:/KBC/questions.xlsx"
    wb.save(out_path)
    print(f"wrote {total} questions to {out_path}")


if __name__ == "__main__":
    main()
